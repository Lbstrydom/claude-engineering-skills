/**
 * Every Gemini client takes its options from lib/gemini-client.mjs, which pins
 * the API version. Synced tooling runs on the CONSUMER's `@google/genai`: 3.x
 * defaults to `v1`, where `gemini-*-latest` 404s and `systemInstruction` is
 * rejected (a consumer's `/brainstorm` Gemini voice, 2026-11-27). This repo is
 * on 2.x, whose default is `v1beta`, so nothing here would ever notice — the
 * census is the guard.
 */
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { GoogleGenAI } from '@google/genai';
import { geminiClientOptions, GEMINI_API_VERSION } from '../scripts/lib/gemini-client.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const SCRIPTS = path.join(ROOT, 'scripts');

function* scriptFiles() {
  for (const rel of fs.readdirSync(SCRIPTS, { recursive: true })) {
    if (!/\.(mjs|js|cjs)$/.test(rel)) continue;
    if (rel.split(path.sep).includes('.claude-skills')) continue; // generated byte copy
    const abs = path.join(SCRIPTS, rel);
    if (fs.statSync(abs).isFile()) yield { rel: rel.split(path.sep).join('/'), src: fs.readFileSync(abs, 'utf-8') };
  }
}

export function unpinnedConstructions(src) {
  const out = [];
  const re = /new\s+GoogleGenAI\s*\(\s*([^)]*)\)/g;
  let m;
  while ((m = re.exec(src))) {
    if (!/^geminiClientOptions\s*\(/.test(m[1].trim())) out.push(m[0]);
  }
  return out;
}

describe('Gemini clients pin their API version', () => {
  it('no script constructs a GoogleGenAI client without geminiClientOptions()', () => {
    const offenders = [];
    let seen = 0;
    for (const { rel, src } of scriptFiles()) {
      if (!src.includes('GoogleGenAI')) continue;
      const bad = unpinnedConstructions(src);
      seen += (src.match(/new\s+GoogleGenAI\s*\(/g) || []).length;
      for (const b of bad) offenders.push(`${rel}: ${b}`);
    }
    assert.ok(seen >= 14, `vacuous-pass guard: expected >=14 constructions, saw ${seen}`);
    assert.deepEqual(offenders, [], 'route these through geminiClientOptions() (scripts/lib/gemini-client.mjs)');
  });

  it('the census detector flags the old shape and passes the pinned one (its own control)', () => {
    assert.equal(unpinnedConstructions('new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY })').length, 1);
    assert.equal(unpinnedConstructions('new GoogleGenAI({})').length, 1);
    assert.equal(unpinnedConstructions('new GoogleGenAI(geminiClientOptions())').length, 0);
  });

  it('the options pin v1beta, keep the env key, and cannot be overridden by httpOptions', () => {
    assert.equal(GEMINI_API_VERSION, 'v1beta');
    const o = geminiClientOptions({ httpOptions: { apiVersion: 'v1', timeout: 5 } });
    assert.equal(o.httpOptions.apiVersion, 'v1beta');
    assert.equal(o.httpOptions.timeout, 5);
    assert.equal(geminiClientOptions({ apiKey: 'k' }).apiKey, 'k');
  });

  it('a client built from them really targets v1beta (the SDK reads the option)', () => {
    const c = new GoogleGenAI(geminiClientOptions({ apiKey: 'test-not-a-key' }));
    assert.equal(c.apiClient?.clientOptions?.httpOptions?.apiVersion, 'v1beta');
  });
});
