#!/usr/bin/env node
/**
 * @fileoverview Dev-time migration GENERATOR — run ONCE, locally, by the plan
 * author (or `/cycle`), never at deploy/runtime and never by anyone else
 * (consumer-friction-doctor plan §2.4).
 *
 * Reads the Phase-3 ledger (`scripts/upstream-dispositions.json`) and WRITES
 * a migration file's SQL content to disk: one literal `UPDATE` per ledger
 * entry, then a generated catch-all for any terminal row the ledger doesn't
 * cover (a report closed between generation and deployment), then the
 * `chk_upstream_terminal_has_disposition` constraint. It never opens a DB
 * pool: it is a text generator over a local JSON file, plus the same
 * referential checks `check-upstream-probe-coverage.mjs` runs (registry +
 * tracked-test-file reads) run again here before generating SQL (round-2
 * audit H2/M13 — shape validity alone doesn't mean a `probe:`/`test:` value
 * actually resolves, or that the ledger has no duplicate issueId). None of
 * this opens a network connection or reads a credential, so
 * `--selfcheck-relocation` needs no special import-ordering care the way a
 * DB-touching CLI entry point would (contrast `setup-postgres.mjs`,
 * `check-setup.mjs`).
 *
 * Usage:
 *   node scripts/backfill-upstream-dispositions.mjs \
 *     --ledger scripts/upstream-dispositions.json \
 *     --out supabase/migrations/20260820130000_upstream_disposition_required.sql
 *   node scripts/backfill-upstream-dispositions.mjs --dry-run   # print, write nothing
 *
 * Source-repo-only: never declared in sync-to-repos.mjs, never in
 * CLI_SMOKE_SET (§9 — same reasoning as the ledger it reads).
 *
 * @module scripts/backfill-upstream-dispositions
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertKnownFlags, ArgvError } from './lib/cli-io.mjs';
import {
  validateLedgerEntryShape, computeDispositionDivergences, LEGACY_UNTRACKED_TRANSITION,
} from './lib/upstream/dispositions.mjs';
import { probeIds } from './lib/doctor/registry.mjs';
import { readTrackedTestFiles } from './check-upstream-probe-coverage.mjs';

const KNOWN_FLAGS = ['--ledger', '--out', '--dry-run', '--selfcheck-relocation'];
const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Round-2 audit M4: a bare `process.argv[i+1] ?? dflt` collapses "flag
 * absent" and "flag present but the next token is another flag / missing"
 * into the same silent default — `--ledger --out foo.sql` would silently
 * read the DEFAULT ledger instead of erroring on the swallowed value.
 */
function argVal(name, dflt) {
  // Round-6 audit H2: only recognized `--name value` (space-separated) —
  // `--name=value` silently fell through to `i === -1` and returned the
  // DEFAULT, so a supported-looking `--ledger=<path>` invocation quietly
  // selected the wrong ledger rather than erroring or honouring it.
  const eq = process.argv.find((a) => a.startsWith(`--${name}=`));
  if (eq) {
    const v = eq.slice(name.length + 3);
    if (!v) throw new Error(`--${name}= was given with no usable value`);
    return v;
  }
  const i = process.argv.indexOf(`--${name}`);
  if (i === -1) return dflt;
  const next = process.argv[i + 1];
  if (next === undefined || next.startsWith('--')) {
    throw new Error(`--${name} was given with no usable value (missing, or the next token looks like another flag)`);
  }
  return next;
}

/** `disposition.value` is free-text prose for `exempt:` and will contain an
 * apostrophe eventually (Gemini-round-2 G1) — escape before interpolating. */
function sqlEscape(s) {
  return String(s).replaceAll("'", "''");
}

function dispositionLiteral(d) {
  return `${d.kind}:${d.value}`;
}

/**
 * Pure: ledger entries in, migration SQL text out. Separated from `main()`
 * so it is unit-testable without argv/fs.
 * @param {Array<{issueId: string, disposition: {kind: string, value: string}}>} entries
 * @param {string} ledgerRelPath for the header comment only
 * @returns {string}
 */
export function generateBackfillSql(entries, ledgerRelPath) {
  const lines = [
    '-- GENERATED by scripts/backfill-upstream-dispositions.mjs — review before applying.',
    `-- Source ledger: ${ledgerRelPath} (${entries.length} entries)`,
    '--',
    "-- One literal UPDATE per ledger entry, a generated catch-all for any terminal row",
    "-- closed between generation and deployment (Gemini-round-1 G1 — a time-of-generation-",
    "-- to-time-of-deployment race), then the NOT-NULL-equivalent constraint. All three in",
    "-- this ONE file so setup-postgres.mjs --migrate's normal single-transaction-per-file",
    '-- execution guarantees the constraint never exists without the data that satisfies it.',
    '',
  ];

  for (const entry of entries) {
    lines.push(
      `UPDATE upstream_issues SET disposition = '${sqlEscape(dispositionLiteral(entry.disposition))}' `
      // `id` is the table's primary key (globally unique), so this WHERE
      // already targets exactly one row — no repo_id/tenant predicate adds
      // precision. `AND disposition IS NULL` DOES add something real
      // (round-2 audit H1): it makes a re-run of this generator against an
      // already-migrated DB a no-op instead of silently clobbering a
      // disposition set by a later, independent write (e.g. the reconciler).
      // `AND state = '<entry.state>'` (round-5 audit H4): the ledger was
      // researched against a specific lifecycle state at generation time —
      // if the issue transitioned to a DIFFERENT state before this migration
      // deployed (e.g. reopened, or moved fixed -> wont_fix), applying the
      // researched disposition to the now-wrong state would misrepresent
      // why THAT state was reached. A row whose current state no longer
      // matches simply doesn't get updated by this line — it falls through
      // to the catch-all + reconciler's needsReview, the same visible,
      // actionable path an unmatched id already takes.
      + `WHERE id = '${sqlEscape(entry.issueId)}' AND state = '${sqlEscape(entry.state)}' AND disposition IS NULL;`,
    );
  }

  lines.push(
    '',
    "-- Catch-all: any terminal row not covered by the ledger above (closed in the window",
    "-- between this file's generation and its deployment). Caught and closed manually on the",
    '-- next `upstream list --worksheet` via the reconciler, never silently forgotten.',
    `UPDATE upstream_issues SET disposition = '${LEGACY_UNTRACKED_TRANSITION}'`,
    "  WHERE state IN ('fixed','wont_fix') AND disposition IS NULL;",
    '',
    'ALTER TABLE upstream_issues',
    '  DROP CONSTRAINT IF EXISTS chk_upstream_terminal_has_disposition;',
    'ALTER TABLE upstream_issues',
    '  ADD CONSTRAINT chk_upstream_terminal_has_disposition',
    "    CHECK ((state IN ('fixed','wont_fix')) = (disposition IS NOT NULL));",
    '',
    'COMMENT ON CONSTRAINT chk_upstream_terminal_has_disposition ON upstream_issues IS',
    "  'Every terminal (fixed|wont_fix) row must carry a disposition, and no non-terminal row may. Enforced at the DB boundary because the CLI-level check in upstreamTransition is necessary but not sufficient — a future second writer must not be able to bypass it.';",
    '',
  );

  return lines.join('\n');
}

function main() {
  if (process.argv.includes('--selfcheck-relocation')) { console.log('OK'); process.exit(0); }

  try {
    assertKnownFlags(process.argv, KNOWN_FLAGS, { cli: 'backfill-upstream-dispositions' });
  } catch (err) {
    if (err instanceof ArgvError) { process.stderr.write(`${err.message}\n`); process.exit(2); return; }
    throw err;
  }

  let ledgerPath, outPath;
  try {
    ledgerPath = path.resolve(REPO_ROOT, argVal('ledger', 'scripts/upstream-dispositions.json'));
    outPath = argVal('out', null);
  } catch (err) {
    process.stderr.write(`backfill-upstream-dispositions: ${err.message}\n`);
    process.exit(2);
    return;
  }
  const dryRun = process.argv.includes('--dry-run');

  if (!dryRun && !outPath) {
    process.stderr.write('backfill-upstream-dispositions: --out <path> is required unless --dry-run is passed\n');
    process.exit(2);
    return;
  }

  let ledger;
  try {
    ledger = JSON.parse(fs.readFileSync(ledgerPath, 'utf-8'));
  } catch (err) {
    process.stderr.write(`backfill-upstream-dispositions: cannot read ${ledgerPath}: ${err.message}\n`);
    process.exit(1);
    return;
  }
  const entries = Array.isArray(ledger?.entries) ? ledger.entries : [];
  if (entries.length === 0) {
    process.stderr.write(`backfill-upstream-dispositions: ${ledgerPath} has zero entries — refusing to generate an empty backfill.\n`);
    process.exit(1);
    return;
  }

  // Round-1 audit H2: this generator used to trust unvalidated ledger data —
  // a malformed entry (bad issueId shape, missing disposition, wrong state)
  // would still produce a syntactically valid but semantically wrong SQL
  // statement. Fail closed on the FIRST malformed entry rather than
  // generating a migration from data that never passed the schema the gate
  // itself enforces.
  const shapeProblems = entries.flatMap((e, i) => {
    const problems = validateLedgerEntryShape(e);
    return problems.map((p) => `entry[${i}] (issueId ${JSON.stringify(e?.issueId)}): ${p}`);
  });
  if (shapeProblems.length > 0) {
    process.stderr.write(
      `backfill-upstream-dispositions: ${ledgerPath} has ${shapeProblems.length} shape-invalid entr${shapeProblems.length === 1 ? 'y' : 'ies'} — refusing to generate SQL from unvalidated data:\n`
      + shapeProblems.map((p) => `  - ${p}\n`).join(''),
    );
    process.exit(1);
    return;
  }

  // Round-2 audit H2/M13: shape validity says an entry LOOKS like a
  // disposition; it says nothing about whether `probe:<id>` resolves in the
  // registry, `test:<path>` is actually tracked, or the ledger has two
  // entries fighting over one issueId. Run the exact same referential check
  // `upstream:coverage:gate` enforces, HERE, before any SQL is generated —
  // a ledger that would fail that gate must never reach a migration file.
  let divergences = [];
  try {
    const trackedResult = readTrackedTestFiles();
    ({ divergences } = computeDispositionDivergences({
      ledgerEntries: entries,
      registryProbeIds: probeIds(),
      trackedTestFiles: trackedResult.files,
    }));
  } catch (err) {
    process.stderr.write(`backfill-upstream-dispositions: could not verify referential validity: ${err.message}\n`);
    process.exit(1);
    return;
  }
  if (divergences.length > 0) {
    process.stderr.write(
      `backfill-upstream-dispositions: ${ledgerPath} has ${divergences.length} referential divergence${divergences.length === 1 ? '' : 's'} — refusing to generate SQL (run \`node scripts/check-upstream-probe-coverage.mjs\` for detail):\n`
      + divergences.map((d) => `  - ${d}\n`).join(''),
    );
    process.exit(1);
    return;
  }

  const sql = generateBackfillSql(entries, path.relative(REPO_ROOT, ledgerPath).replaceAll('\\', '/'));

  if (dryRun) {
    process.stdout.write(sql);
    process.exit(0);
    return;
  }

  const resolvedOut = path.resolve(REPO_ROOT, outPath);
  fs.mkdirSync(path.dirname(resolvedOut), { recursive: true });
  fs.writeFileSync(resolvedOut, sql);
  process.stderr.write(`  wrote ${entries.length} backfill UPDATE(s) + the terminal-disposition constraint to ${resolvedOut}\n`);
  process.exit(0);
}

const invokedDirectly = import.meta.url === `file://${process.argv[1]}`
  || process.argv[1]?.endsWith('backfill-upstream-dispositions.mjs');

if (invokedDirectly) main();
