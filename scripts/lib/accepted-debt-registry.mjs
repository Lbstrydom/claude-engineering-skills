/**
 * Validate a registry array (defaulting to `ACCEPTED_DEBT_ROWS`) against
 * the Zod schema. Never throws — returns a discriminated result so a
 * malformed registry becomes a handled operational error, not an uncaught
 * module-evaluation crash.
 * @param {object[]} [rows]
 * @returns {{ok: true, rows: object[]} | {ok: false, error: string}}
 */
export function loadRegistry(rows = ACCEPTED_DEBT_ROWS) {
  const parsed = AcceptedDebtRegistrySchema.safeParse(rows);
  if (!parsed.success) {
    return { ok: false, error: parsed.error.message.slice(0, 2000) };
  }
  return { ok: true, rows: parsed.data };
}
