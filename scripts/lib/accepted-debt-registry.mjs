/**
 * @fileoverview The single source of truth for what this repo currently
 * believes about each row of AGENTS.md's "Accepted Technical Debt" table.
 *
 * Raw data + a separate `loadRegistry()` loader — the array is exported
 * UNVALIDATED and validation happens only inside `loadRegistry()`, never at
 * import time. A static ESM import evaluates before any CLI error boundary
 * exists, so import-time validation would crash the process with Node's own
 * uncaught-module-evaluation exit code rather than this tool's exit-2
 * contract. `main()` calls `loadRegistry()` inside its own try/catch; tests
 * call it directly with a fixture array.
 *
 * `rowFingerprint` values are generated by running `parseAgentsDebtTable`
 * against the current AGENTS.md content and pasting the output in — never
 * hand-typed, since a hand-typed fingerprint could silently disagree with
 * the cell text it's supposed to represent.
 *
 * Design: docs/plans/accepted-debt-table-verification.md §2/§4.
 *
 * @module scripts/lib/accepted-debt-registry
 */

import { z } from 'zod';

const PredicateSchema = z.object({
  type: z.literal('no-invocation-outside-scope'),
  symbol: z.string().min(1),
  provenanceModules: z.array(z.string().min(1)).min(1),
  allowedGlobs: z.array(z.string().min(1)),
}).strict();

const VerificationSchema = z.discriminatedUnion('mode', [
  z.object({ mode: z.literal('checked'), predicate: PredicateSchema }).strict(),
  z.object({ mode: z.literal('unverifiable'), reason: z.string().min(1) }).strict(),
]);

const AcceptedDebtRowSchema = z.object({
  id: z.string().min(1),
  agentsTableAnchor: z.string().min(1),
  // 16 lowercase hex chars — the exact shape computeRowFingerprint() (sha(),
  // len 16) produces. A bare .min(1) let a malformed value through (GPT
  // Sustainability L4).
  rowFingerprint: z.string().regex(/^[0-9a-f]{16}$/, 'must be a 16-char lowercase hex fingerprint'),
  verification: VerificationSchema,
}).strict();

// Collection-level: per-row `.strict()` parsing alone doesn't establish
// uniqueness across the array — two rows claiming the same live table row
// with conflicting `verification` would make the report's meaning
// ambiguous, so both `id` and `agentsTableAnchor` must be unique.
const AcceptedDebtRegistrySchema = z.array(AcceptedDebtRowSchema).superRefine((rows, ctx) => {
  const seenIds = new Set();
  const seenAnchors = new Set();
  for (const row of rows) {
    if (seenIds.has(row.id)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: `duplicate id: ${row.id}` });
    }
    seenIds.add(row.id);
    if (seenAnchors.has(row.agentsTableAnchor)) {
      ctx.addIssue({ code: z.ZodIssueCode.custom, message: `duplicate agentsTableAnchor: ${row.agentsTableAnchor}` });
    }
    seenAnchors.add(row.agentsTableAnchor);
  }
});

