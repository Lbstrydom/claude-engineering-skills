-- Unified arm-evaluation framework — persistence (blinded Claude-judge).
--
-- Plan: docs/plans/arm-eval-framework.md (Cluster A, Phase 3 / §10.1). The full
-- evaluation lifecycle at the SESSION grain (a session groups ALL arms' outputs
-- for one task so the judge ranks the set + the human anchor is computable).
-- Additive + idempotent (CREATE … IF NOT EXISTS / ADD COLUMN IF NOT EXISTS /
-- CREATE OR REPLACE VIEW); no clocks/network → re-runs byte-identically.
--
-- Claude is the JUDGE, never an arm (enforced in code: experiments.mjs). RLS is
-- ENABLED (deny-all; the single-tenant runtime role owns `public` and bypasses
-- RLS — mirrors security_incidents), so no non-owner can read experiment rows.

-- ── 1. arm_eval_sessions — the SESSION grain (groups all arms for one task) ──
CREATE TABLE IF NOT EXISTS arm_eval_sessions (
  session_id      uuid PRIMARY KEY,
  repo_id         uuid,                 -- multi-repo store: scope like every other table
  experiment_type text NOT NULL CHECK (experiment_type IN ('plan-authoring', 'brainstorm', 'auditor')),
  task_id         text NOT NULL,        -- canonical task-text hash (diversity unit)
  phase           text CHECK (phase IS NULL OR phase IN ('calibration', 'prospective')),
  config_version  text,
  rubric_version  text,
  seed            bigint,               -- blinded presentation-order RNG seed (replay)
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS arm_eval_sessions_type_task_idx ON arm_eval_sessions (experiment_type, task_id);
CREATE INDEX IF NOT EXISTS arm_eval_sessions_repo_idx ON arm_eval_sessions (repo_id) WHERE repo_id IS NOT NULL;

-- ── 2. arm_eval_runs — one arm's execution within a session ──────────────────
CREATE TABLE IF NOT EXISTS arm_eval_runs (
  run_id           uuid PRIMARY KEY,
  session_id       uuid NOT NULL REFERENCES arm_eval_sessions(session_id),
  arm              text NOT NULL,
  resolved_model   jsonb,               -- concrete provider/model/version/pricing AT RUN TIME (reproducibility)
  context_pack_hash text,
  budget_lease_id  bigint,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS arm_eval_runs_session_arm_uk ON arm_eval_runs (session_id, arm);

-- ── 3. arm_eval_outputs — the produced artifact + conformance ────────────────
CREATE TABLE IF NOT EXISTS arm_eval_outputs (
  run_id             uuid NOT NULL REFERENCES arm_eval_runs(run_id),
  output_hash        text NOT NULL,
  output_ref         text,             -- stored artifact path/blob
  producer_conformant boolean NOT NULL DEFAULT true,
  normalized         boolean NOT NULL DEFAULT false,   -- blinding-leak normalization applied
  PRIMARY KEY (run_id, output_hash)
);

-- ── 4. arm_eval_judgments — per-(run × pass) rubric scores ───────────────────
CREATE TABLE IF NOT EXISTS arm_eval_judgments (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id             uuid NOT NULL REFERENCES arm_eval_runs(run_id),
  output_hash        text NOT NULL,
  judge_pass         integer NOT NULL,   -- 1 | 2 (double-pass self-consistency)
  presentation_order integer,
  rubric_version     text,
  scores             jsonb NOT NULL,     -- { dimension: 1..5 }
  created_at         timestamptz NOT NULL DEFAULT now(),
  -- Composite FK (audit R1 792b5787): a judgment must reference an output that
  -- actually exists for that run — not just any run.
  FOREIGN KEY (run_id, output_hash) REFERENCES arm_eval_outputs(run_id, output_hash)
);
CREATE UNIQUE INDEX IF NOT EXISTS arm_eval_judgments_run_pass_uk ON arm_eval_judgments (run_id, output_hash, judge_pass);

-- ── 5. arm_eval_human_rankings — the BLINDED human anchor (ranked labels) ────
-- The reviewer ranks OPAQUE labels (output-A/B/C); the label→arm map is derived
-- post-hoc from the session seed (never shown). Kendall τ is computed after
-- unblinding — this preserves blinding while making the anchor computable.
CREATE TABLE IF NOT EXISTS arm_eval_human_rankings (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id    uuid NOT NULL REFERENCES arm_eval_sessions(session_id),
  ranked_labels jsonb NOT NULL,        -- ordered opaque labels, best→worst
  reviewer      text,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS arm_eval_human_rankings_session_idx ON arm_eval_human_rankings (session_id);

-- ── 6. arm_eval_crosschecks — objective cross-check results per run ──────────
CREATE TABLE IF NOT EXISTS arm_eval_crosschecks (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id        uuid NOT NULL REFERENCES arm_eval_runs(run_id),
  check_name    text NOT NULL,
  check_version text,
  status        text NOT NULL,         -- ok | flag | unavailable | error
  score         numeric,               -- e.g. accepted-weighted defect load
  findings      jsonb,
  evidence_refs jsonb,
  failure_reason text,
  created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS arm_eval_crosschecks_run_idx ON arm_eval_crosschecks (run_id, check_name);

-- ── 7. audit_runs + spend-ledger linkage (nullable — don't break existing) ──
-- The plan audit-proxy stamps the fixed-auditor audit_runs row so it joins 1:1
-- back to the arm's run (Gemini-R2 fix: session_id is 1:many; arm_eval_run_id
-- is unique per (session × arm)). Existing rows stay null (no backfill).
ALTER TABLE audit_runs           ADD COLUMN IF NOT EXISTS author_model     text;
ALTER TABLE audit_runs           ADD COLUMN IF NOT EXISTS task_id          text;
ALTER TABLE audit_runs           ADD COLUMN IF NOT EXISTS arm_eval_run_id  uuid;
ALTER TABLE model_ab_spend_ledger ADD COLUMN IF NOT EXISTS arm_eval_run_id uuid;
CREATE INDEX IF NOT EXISTS audit_runs_arm_eval_run_idx ON audit_runs (arm_eval_run_id) WHERE arm_eval_run_id IS NOT NULL;

-- ── 8. RLS (deny-all; owner bypasses — mirrors security_incidents) ───────────
DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['arm_eval_sessions','arm_eval_runs','arm_eval_outputs','arm_eval_judgments','arm_eval_human_rankings','arm_eval_crosschecks']
  LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
  END LOOP;
END $$;

-- ── 9. arm_eval_leaderboard — per (experiment × arm) aggregate ───────────────
-- Raw inputs the decision module folds; the decision (arm-eval/decision.mjs)
-- computes the two-level verdict in JS. This view just surfaces the persisted
-- counts for the CLI + dashboards.
CREATE OR REPLACE VIEW arm_eval_leaderboard AS
SELECT
  s.repo_id,                                                             -- multi-repo scope (audit R1 9f4a31bc)
  s.experiment_type,
  r.arm,
  COUNT(DISTINCT s.session_id)                                            AS sessions,
  COUNT(DISTINCT s.task_id)                                               AS distinct_tasks,
  COUNT(DISTINCT o.run_id) FILTER (WHERE o.producer_conformant)           AS conformant_runs,
  COUNT(DISTINCT o.run_id)                                                AS total_runs,
  COUNT(DISTINCT j.id)                                                    AS judgments,
  s.phase
FROM arm_eval_sessions s
JOIN arm_eval_runs r      ON r.session_id = s.session_id
LEFT JOIN arm_eval_outputs o ON o.run_id = r.run_id
LEFT JOIN arm_eval_judgments j ON j.run_id = r.run_id
GROUP BY s.repo_id, s.experiment_type, r.arm, s.phase;

COMMENT ON VIEW arm_eval_leaderboard IS
  'Arm-eval per (experiment_type × arm × phase) aggregate: sessions, distinct tasks, conformant/total runs, judgment count. The decision module (arm-eval/decision.mjs) computes the two-level gate→rank verdict + human anchor from the finer judgment/human-ranking/crosscheck rows.';
